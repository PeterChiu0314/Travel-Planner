  await expect(page.getByRole("table",{name:"實付明細",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"新增實付",exact:true}).click();
  await expect(page.getByRole("form",{name:"實付編輯"}).getByLabel("項目",{exact:true})).toHaveValue("");
